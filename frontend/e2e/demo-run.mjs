// Plays demo steps 2 to 5 in mock mode and screenshots each stage.
import { chromium } from '@playwright/test'
const base = process.env.BASE ?? 'http://localhost:5173'
const [w, h] = (process.env.SIZE ?? '390x844').split('x').map(Number)
const out = 'e2e/screens'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: w, height: h } })
const page = await ctx.newPage()
const errors = []
page.on('console', (m) => (m.type() === 'error' || m.type() === 'warning') && errors.push(`${m.type()}: ${m.text()}`))
page.on('pageerror', (e) => errors.push(`pageerror: ${e.message}`))
const t0 = Date.now()
const log = (s) => console.log(((Date.now() - t0) / 1000).toFixed(1) + 's', s)
await page.goto(base + '/')
await page.evaluate(() => { localStorage.clear(); sessionStorage.clear() })
await page.goto(base + '/r/run_demo')
await page.waitForURL(/signin/)
await page.getByRole('button', { name: /Continue as Jordan/ }).click()
await page.waitForURL(/\/r\/run_demo/)
log('signed in, on join page')
await page.getByRole('button', { name: /Chicken Burrito/ }).click()
await page.waitForTimeout(400)
await page.screenshot({ path: `${out}/demo-1-item-${w}.png` })
await page.getByRole('button', { name: /Add to order/ }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${out}/demo-2-cart-${w}.png` })
await page.locator('#cart-bar').click()
await page.waitForURL(/checkout/)
await page.waitForTimeout(600)
await page.screenshot({ path: `${out}/demo-3-checkout-${w}.png`, fullPage: true })
await page.getByRole('button', { name: /^Place order/ }).click()
await page.waitForURL(/\/o\//)
log('order placed ' + page.url())
await page.waitForTimeout(1200)
await page.screenshot({ path: `${out}/demo-4-placed-${w}.png` })
await page.getByText(/bought your food/).waitFor({ timeout: 40000 })
log('purchased')
await page.waitForTimeout(800)
await page.screenshot({ path: `${out}/demo-5-purchased-${w}.png` })
await page.getByText(/is on the way/).waitFor({ timeout: 20000 })
log('picked up')
await page.waitForTimeout(20000)
await page.screenshot({ path: `${out}/demo-6-walking-${w}.png` })
await page.getByText(/is here/).waitFor({ timeout: 70000 })
log('arrived')
await page.screenshot({ path: `${out}/demo-7-arrived-${w}.png`, fullPage: true })
await page.getByRole('button', { name: 'Got it' }).click()
await page.waitForTimeout(900)
await page.screenshot({ path: `${out}/demo-8-celebrate-${w}.png` })
log('celebrated')
await page.getByRole('button', { name: 'Enjoy your food' }).click()
await page.getByText('Dana wants to meet again').first().waitFor({ timeout: 20000 })
log('invite banner')
await page.screenshot({ path: `${out}/demo-9-invite-${w}.png` })
console.log(errors.length ? errors.join('\n') : 'no console errors')
await browser.close()
