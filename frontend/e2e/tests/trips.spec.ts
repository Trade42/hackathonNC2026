test('a signed-in account with no circle sees open trips but can’t open one', async ({ page }) => {
  await freshMock(page)
  await signInAs(page, 'judge')
  await page.evaluate(() => {
    const key = 'ferry.mock.v6'
    const state = JSON.parse(localStorage.getItem(key)!)
    for (const circle of state.circles) circle.members = circle.members.filter((member: { id: string }) => member.id !== 'usr_judge')
    localStorage.setItem(key, JSON.stringify(state))
  })
  await page.reload()
  await expect(page.getByRole('list', { name: 'Ferries leaving soon' })).toContainText('Cosmic Cantina')
  await page.goto('/run/new')
  await expect(page.getByText('You’re not in a group yet. Add @Ferrygo_bot to a Telegram group chat', { exact: false })).toBeVisible()
  await page.getByRole('radio', { name: 'Cosmic Cantina' }).click()
  await expect(page.getByRole('button', { name: 'Open the ferry' })).toBeDisabled()
})

