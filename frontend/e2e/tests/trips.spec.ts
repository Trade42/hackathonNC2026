import { expect, test } from '@playwright/test'
import { checkA11y, freshMock, noHorizontalScroll, shot, signInAs, watchConsole } from './helpers'

test('a runner shares the return place, time and walking zone', async ({ page }, info) => {
  const problems = watchConsole(page)
  await freshMock(page)
  await signInAs(page, 'maya', '/run/new')
  await expect(page.getByRole('heading', { name: 'Where are you going?' })).toBeVisible()
  await page.getByRole('radio', { name: 'Cosmic Cantina' }).click()
  await page.getByRole('button', { name: /^Heading back to:/ }).click()
  const picker = page.getByRole('dialog', { name: 'Where are you heading back to?' })
  await expect(picker).toBeVisible()
  await picker.getByRole('button', { name: 'Hinton James lobby' }).click()
  await picker.getByRole('slider', { name: /Drops off within/ }).fill('800')
  await picker.getByRole('button', { name: 'Use this spot' }).click()
  await expect(page.getByRole('button', { name: /Heading back to: Hinton James lobby.*800 m/ })).toBeVisible()
  await noHorizontalScroll(page)
  await checkA11y(page, 'new trip')
  await shot(page, info, 'new-trip')
  const created = page.waitForResponse((response) => response.url().endsWith('/v1/runs') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Open the ferry' }).click()
  const run = await (await created).json() as { leaving_at: string; window_closes_at: string }
  expect(Date.parse(run.window_closes_at) - Date.parse(run.leaving_at)).toBe(10 * 60_000)
  await page.waitForURL(/\/run\/run_/)
  const runId = new URL(page.url()).pathname.split('/').at(-1)
  await page.goto('/settings')
  await page.getByRole('button', { name: 'Sign out' }).click()
  await signInAs(page, 'judge', `/r/${runId}`)
  await expect(page.getByText(/Hinton James lobby/).first()).toBeVisible()
  await expect(page.getByText(/800 m/).first()).toBeVisible()
  expect(problems).toEqual([])
})

